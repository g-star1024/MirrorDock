/**
 * MirrorDock 界面语言支持（X10-160）
 *
 * 设计取舍：现有 UI 有近 2000 处中文文案，逐处包 t() 会制造大量 JSX 改动与回归风险。
 * 因此采用「词典 + DOM 桥接」：React 照旧以中文渲染，桥接层在 locale=en 时把已渲染的
 * 文本节点与可访问属性替换为词典里的英文；切回中文时按记录还原。新增文案只需往词典
 * 补一条，不需要改组件。词典未命中的文案保持中文（不伪造翻译）。
 *
 * 不翻译用户数据：设备名、文件名、路径、错误原文（来自后端）只有在与词典键**完全相同**
 * 时才会被替换，且只做整段/短语精确匹配，不音译、不改写动态内容。
 */
import { useEffect } from "react";

export type Locale = "zh" | "en";

const LOCALE_KEY = "mirrordock.locale";

export function readLocale(): Locale {
  try {
    return localStorage.getItem(LOCALE_KEY) === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export function writeLocale(next: Locale): void {
  try {
    localStorage.setItem(LOCALE_KEY, next);
  } catch {
    /* 存储不可用时本次会话仍生效 */
  }
  document.documentElement.lang = next === "en" ? "en" : "zh-CN";
}

