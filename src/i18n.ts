if (typeof window !== "undefined") {
  (window as unknown as Record<string, unknown>).__mdI18n = { applyLocale, translateText, EN };
}

/** React 桥接：语言变化时应用，并监听后续 DOM 更新（动态渲染的视图也要翻译）。 */
export function useLocaleBridge(locale: Locale): void {
  useEffect(() => {
    const root = document.getElementById("root");
    if (!root) return;
    // 注意：不要用 requestAnimationFrame 调度——离线/后台 WKWebView 不跑 display link，
    // rAF 回调永远不会触发（X10-160 在真实 WKWebView 探针中实测踩到）。
    let applying = false;
    const apply = () => {
      if (applying) return;
      applying = true;
      applyLocale(root, locale);
      applying = false;
    };
    apply();
    const observer = new MutationObserver(apply);
    observer.observe(root, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: [...ATTRS],
    });
    return () => observer.disconnect();
  }, [locale]);
}
